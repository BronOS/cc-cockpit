// Persisted record shapes shared by main and (later) the renderer. Plain data only: no Electron,
// no Node imports, so the renderer bundle can import this file.
//
// Every record carries `schemaVersion` (the JSON store stamps it on write and quarantines files
// that do not match); see src/main/store/json-file.ts.
import type { LayoutState } from './layout'
import type { ProjectColor } from './project-color'
import type { RemoteServer } from './remote-servers'
import type { TerminalFont } from './terminal-font'
import type { WindowBackground } from './window-background'

/**
 * What a tab runs: `claude` (with our hooks), the user's login shell, or a command line from the
 * user's new-tab menu entries (`TabCommandEntry`), run by that login shell.
 */
export type TabKind = 'claude' | 'shell' | 'command'

/**
 * One user-defined entry of the new-tab menu (design §3 Tabs, "Custom commands"): app-wide in
 * `AppSettings.tabCommands`, per project in `ProjectRecord.tabCommands`. `command` is a shell
 * command line the user wrote (`lazygit`, `npm run dev`, `docker compose logs -f | grep api`),
 * run as `$SHELL -l -i -c <command>` in the project folder. Read back through `tabCommandsOf`
 * (src/main/tabs/tab-commands.ts): the files are user-writable, a bad entry is dropped.
 */
export interface TabCommandEntry {
  /** Minted by main when the entry is added; the menu and `tabs.create` name the entry by it. */
  id: string
  /** The menu item and the tab's (or overlay's) title. */
  label: string
  command: string
  /**
   * Where it runs: a tab (absent, the default) or a terminal overlay over the tabs that closes when
   * its program exits (`lazygit`, `yazi`). Stored only as `'overlay'`: a file written before this
   * field existed, or a damaged value, reads as a tab (checkTabCommandOpen).
   */
  open?: 'overlay'
}

/** Where a new-tab menu entry runs. Only `'overlay'` is ever stored; a tab is the absent default. */
export type TabCommandOpen = 'tab' | 'overlay'

/** Which list a new-tab menu entry comes from. */
export type TabCommandLevel = 'app' | 'project'

/** A tab as persisted for restore (Task 22). Runtime-only state (token, PTY id) is not here. */
export interface TabRecord {
  /** Stable tab id, generated by main. */
  id: string
  kind: TabKind
  /** Absolute; always the project folder or a path inside it. */
  cwd: string
  /** Claude session id, when a SessionStart hook reported one; restore resumes with `--resume`. */
  sessionId?: string
  /**
   * A command tab's own copy of its menu entry, taken when the tab was opened: editing or
   * deleting the entry later does not touch the tab. Restore brings the tab back NOT started.
   */
  label?: string
  command?: string
  /**
   * A plugin's command tab (ctx.sessions.openCommand) instead of `command`: the argv it runs with no
   * shell and the plugin that opened it (with its name then, display only). Restore brings it back
   * not started, and only while that plugin is installed and not revoked (restore.ts).
   */
  argv?: string[]
  openedBy?: string
  openedByName?: string
  /** A Claude tab's name given by the person (shared/session-name.ts); shown over Claude's topic. */
  name?: string
  /**
   * The person's flag on the tab, any kind (shared/tab-flag.ts). Plain data here (the file is
   * user-writable): read back through tabFlagOf, which drops a damaged value.
   */
  flag?: { color: string; note?: string }
}

/**
 * A project window's size and place (`ProjectRecord.bounds`). x/y/width/height are the NORMAL
 * bounds (what un-maximising returns to), also while the window is maximised or full screen; the
 * flags say which of those it was in, and are present only when true. Read back through
 * `sanitizeBounds` (src/main/windows/window-bounds.ts): the file is user-writable.
 */
export interface WindowBounds {
  x?: number
  y?: number
  width: number
  height: number
  maximized?: boolean
  fullScreen?: boolean
}

/** `<data>/projects/<projectId>.json`. */
export interface ProjectRecord {
  schemaVersion: number
  /**
   * First 16 hex chars of sha256 of the real folder path at the time the record was created.
   * After a `relink` the id stays (settings, plugin data and tabs are keyed by it) while `path`
   * changes, so the id no longer equals the hash of `path`; never recompute it from `path`.
   */
  id: string
  /** Real (symlinks resolved) absolute folder path. */
  path: string
  /** Folder basename, for window titles and the picker. */
  name: string
  /** Plugin ids enabled for this project. */
  enabledPlugins: string[]
  /**
   * Plugin ids the user switched off although they are on by default (bundled `enabledByDefault`).
   * Absent in older records = none. A plugin is on when listed in `enabledPlugins`, or when it is
   * default-on and not listed here (`pluginEnabledIn`).
   */
  disabledPlugins?: string[]
  /** pluginId -> project-level plugin settings (validated against the manifest schema later). */
  pluginSettings: Record<string, unknown>
  layout: LayoutState
  tabs: TabRecord[]
  /** This project's entries of the new-tab menu, after the app-wide ones. Absent = none. */
  tabCommands?: TabCommandEntry[]
  bounds?: WindowBounds
  /**
   * The project's colour (shared/project-color.ts): a palette name or a lowercase `#rrggbb`.
   * Absent = none. The file is user-writable, so the registry repairs a damaged value to absent
   * when it loads the record (projectColorOf).
   */
  color?: ProjectColor
  /**
   * This project's own Discuss prompt: key absent = use the global one (AppSettings.discussPrompt),
   * a string (also '' = off for this project) replaces it. Repaired to absent on load like `color`.
   */
  discussPrompt?: string
  /**
   * Plugin services: `{ [service]: pluginId }`, which plugin answers a service that several enabled
   * plugins provide (Settings > Plugins). Absent in older records = no picks. A pick whose plugin is
   * no longer a provider in the project counts as no pick (shared/services.ts selectProvider) and is
   * never cleaned up. The file is user-writable: the registry drops a damaged value when it loads.
   * The reserved key `@open-file` holds the plugin a Sessions panel file click goes to, or
   * `@builtin` for the built-in viewer (shared/services.ts OPEN_FILE_PICK).
   */
  serviceProviders?: Record<string, string>
  /** Epoch ms of the last `openPath`. */
  lastOpenedAt: number
}

/** A record plus whether its folder is still there. `missing` is computed, never persisted. */
export type ProjectView = ProjectRecord & { missing: boolean }

/** `<data>/app.json`. */
export interface AppSettings {
  schemaVersion: number
  /** Project ids whose windows were open at last quit, restored at the next start (Task 22). */
  openProjects: string[]
  /** Most recently opened project ids, newest first, capped (see MAX_RECENT_PROJECTS). */
  recentProjects: string[]
  /** Active theme id; unset means "follow the OS" (Task 10). */
  theme?: string
  /** commandId -> chord overrides (Task 11). */
  keyOverrides: Record<string, string>
  /**
   * What a tab does when its process exits. Absent or anything but 'keep' (the file is
   * user-writable) reads as 'close-clean'.
   */
  tabExit?: TabExitBehavior
  /**
   * Open a Claude tab when a project window opens and nothing came back into it (no restore plan,
   * no plugin tab). Absent or anything but `false` (the file is user-writable) reads as on.
   */
  claudeTabOnOpen?: boolean
  /**
   * The session gist: after a Claude tab's turn ends, Claude Haiku writes a one-line summary of the
   * session from its last prompts (main/sessions/session-gist.ts), shown in the Sessions panel.
   * Off unless exactly `true` (the file is user-writable): each gist is a request on the person's
   * Claude Code login, so it never starts by accident.
   */
  sessionGist?: boolean
  /**
   * Rate limits from the status line: Claude tabs get a `statusLine` in the app's `--settings` file
   * that runs `ccc statusline`, which reports the plan usage, cost and context fill to main and then
   * runs the person's own status line (main/hooks/hooks-file.ts, cli/statusline.ts). On unless
   * exactly `false`: it changes nothing the person sees, and plugins (the usage meter) need it.
   */
  statusLineUsage?: boolean
  /**
   * Plugins' `ctx.notify(text, { sound: true })` ring a short chime in the project window (main's
   * ChimeGate reads it at each ring). Absent or anything but `false` (the file is user-writable)
   * reads as on. Off: no chime, and such notifications stay silent on the OS side too.
   */
  notificationSounds?: boolean
  /**
   * The one sound those notifications ring: `builtin:<name>` or `system:<root>:<path>`
   * (shared/notify-sound.ts). An id, never a path; main checks a system id against a fresh listing
   * of its fixed OS sound folders at every use. Absent or damaged reads as `builtin:chime`.
   */
  notificationSound?: string
  /**
   * Ask before the user closes a tab whose process is still running (a Claude turn, a dev server).
   * Absent or anything but `false` (the file is user-writable) reads as on. Read by the renderer at
   * each close (`settings.confirmTabClose`); closes main or a plugin makes never ask.
   */
  confirmTabClose?: boolean
  /**
   * Which end of each tab the close button (×) sits at. Absent or anything but 'left' (the file is
   * user-writable) reads as 'right', the layout before the setting existed. Pushed to every window
   * (`prefs.changed`), so a change applies to every open tab strip at once.
   */
  tabCloseSide?: TabCloseSide
  /**
   * Legacy (before 0.10): how many changed files the core Sessions panel listed. Only read once at
   * start, to move it to the cockpit.sessions plugin's `filesShown` app setting, then dropped
   * (main/settings/sessions-migration.ts); nothing writes it any more.
   */
  sessionFilesShown?: number
  /**
   * Hide the side zones (right first, then left) while the terminal would be narrower than
   * `minTerminalWidth`, and bring them back as the window widens (renderer/zones/auto-hide.ts).
   * Absent or anything but `false` (the file is user-writable) reads as on. Pushed to every window
   * (`prefs.changed`).
   */
  zoneAutoHide?: boolean
  /**
   * The terminal's minimum width in px for `zoneAutoHide`. Absent or damaged reads as 720
   * (src/shared/zone-auto-hide.ts). Pushed to every window (`prefs.changed`).
   */
  minTerminalWidth?: number
  /**
   * The font every terminal draws with (tabs and terminal overlays), apart from the app UI's.
   * Absent = the defaults; each field that is missing or damaged (the file is user-writable) reads
   * as its own default (main/settings/terminal-font.ts). Pushed to every window (`prefs.changed`).
   */
  terminalFont?: Partial<TerminalFont>
  /**
   * The see-through background of project windows (shared/window-background.ts). Absent = the
   * defaults (opaque); each field that is missing or damaged reads as its own default
   * (main/settings/window-background.ts). `transparent` is read when a project window is created;
   * `opacity` is pushed to every window (`prefs.changed`) and `blur` applied by main to the windows
   * created transparent.
   */
  windowBackground?: Partial<WindowBackground>
  /** App-wide entries of the new-tab menu, after Claude and Shell. Absent = none. */
  tabCommands?: TabCommandEntry[]
  /**
   * Marketplace index URLs (`https:` or `file:`). Absent = the one official index; the file is
   * user-writable, so main drops anything that is not a usable URL (marketplaceUrls).
   */
  marketplaces?: string[]
  /** Look for a newer release once a day (main/updates). Absent or anything but `false` (the file is user-writable) reads as on. */
  updateCheck?: boolean
  /**
   * Text Discuss with Claude appends to every message (shared/discuss.ts). Absent = none. The file is
   * user-writable: the registry repairs a non-string or an oversized value to absent when it loads.
   */
  discussPrompt?: string
  /**
   * Offer to install the `ccc` command at start-up when it is missing (main/hooks/ccc-offer.ts).
   * Absent or anything but `false` reads as on; stored only as `false` ("Don't ask again").
   */
  cccOffer?: boolean
  /** The newest version the user dismissed in the update notice; a newer release shows again. */
  updateDismissed?: string
  /** Plugin id to the git URL it was last installed from; outlives an uninstall (repo-change warning). */
  pluginRepos?: Record<string, string>
  /**
   * Bundled plugin ids switched off in every project ("Off in all projects", Settings > Plugins). Wins
   * over the project records; each record's own switch comes back when the id leaves this list.
   * Absent = none. Only bundled plugins count (main/plugins/enablement.ts offAppWide): the file is
   * user-writable, and a third-party id here is ignored.
   */
  disabledBundled?: string[]
  /** pluginId -> app-wide plugin settings (validated against the manifest schema, Task 26). */
  pluginSettings: Record<string, unknown>
  /**
   * pluginId -> the global values of its project fields (design-next §5.2): every project that does
   * not override a field gets this value, else the schema default. Secret ones live in secrets.json
   * (`setting:projectDefault:<field>`). Absent = defaults only.
   */
  pluginProjectDefaults?: Record<string, unknown>
  /**
   * The one-time migration to global values ran (main/settings/project-defaults-migration.ts): stored
   * project values equal to their schema default were dropped, so they use the global value.
   */
  projectDefaultsMigrated?: true
  /**
   * Web access (design-web.md §4): the gateway that serves the cockpit to a browser. Off unless
   * `enabled` is exactly `true`. The file is user-writable, so main reads it field by field
   * (main/web/settings.ts `webAccessOf`): a damaged field reads as its default, and a network bind
   * whose §4.3 risk was never confirmed is refused (nothing listens), never quietly moved to loopback.
   */
  webAccess?: Partial<WebAccessSettings>
  /**
   * Saved remote servers (design-remote-desktop.md §2). The file is user-writable, so every read goes
   * through `validateRemoteServers` (shared/remote-servers.ts), which caps and repairs it; the device
   * cookie and the SSH password or passphrase of each are stored encrypted (`RemoteServerStore`,
   * main/remote/remote-servers.ts).
   */
  remoteServers?: RemoteServer[]
}

/** How a browser signs in (design-web.md §4.2); every mode ends in the same device cookie. */
export type WebAccessMode = 'link' | 'password' | 'confirm' | 'none'

/**
 * A dangerous choice that needs the person's confirm (design-web.md §4.3): `none-network` is no
 * sign-in on an address other than loopback, `plain-http` is any mode over plain http on one (a
 * network bind with no TLS, or an `http:` external origin on a network name).
 */
export type WebAccessRisk = 'none-network' | 'plain-http'

/** `app.json` › `webAccess` once read (main/web/settings.ts `webAccessOf`, defaults applied). */
export interface WebAccessSettings {
  enabled: boolean
  /**
   * The address to listen on: an IP address or `localhost`. Loopback keeps it on this machine; any
   * other address is the network, allowed with TLS or after the plain-http confirm (§4.3).
   */
  bind: string
  port: number
  /**
   * The origin the browser sees when a proxy is in front (`https://box.tailnet.ts.net`), as an
   * origin (scheme, host, port; no path). Absent: the gateway's own `http://<host>` origins only.
   */
  externalOrigin?: string
  /** Extra Host names the person allows (`name` or `name:port`), normalised to `host:port`. */
  hosts: string[]
  mode: WebAccessMode
  /** Certificate and key files (PEM, absolute paths): present, the gateway serves https. */
  tls?: { certPath: string; keyPath: string }
  /**
   * The §4.3 risks the person confirmed, set by a confirmed change on the settings page and kept
   * only while web access stays on with the risk and the exposure it was confirmed for (a change
   * that removes the risk, widens it with another bind, origin or TLS, or turns web access off drops
   * it, so coming back asks again). A risk of the settings not listed here is refused (nothing
   * listens): a hand-edited bind of 0.0.0.0 alone never listens on the network. Not a seal: whoever
   * can write `app.json` can write this list too, the same trust as turning web access on.
   */
  confirmed?: WebAccessRisk[]
  /**
   * Server mode's folder browser starts here (design-web.md §9.8; `ccc web set --start-folder`): an
   * absolute, normalized path. Absent = the server user's home folder; a folder that is gone when
   * the browser asks falls back to home with a note (main/web/list-folders.ts).
   */
  startFolder?: string
}

/**
 * 'close-clean' (default): a tab whose process exits with code 0 and no signal (`/exit`, Ctrl+D,
 * a shell's `exit`) closes as if the user clicked Close; any other exit keeps the tab with its
 * "exited (code N): Restart · Close" banner, so a failure stays visible. 'keep': every exited tab
 * stays, with the banner.
 */
export type TabExitBehavior = 'close-clean' | 'keep'

/** Where a tab's close button sits: before its label ('left') or after it ('right', the default). */
export type TabCloseSide = 'left' | 'right'
