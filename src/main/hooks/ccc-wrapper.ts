// `<data>/bin/ccc`: the launcher for the CLI. Claude's hook commands and the user's shell tabs run
// it; it starts the Electron binary the app itself runs on, as plain Node, on the bundled CLI.
// That needs no `node` on the PATH Claude hands to hook commands (a GUI app's PATH is minimal),
// and the CLI is always the version that belongs to the running app. Regenerated at every start:
// the Electron binary and `out/cli/index.js` move between dev and packaged builds.
import { join } from 'node:path'
import { shellQuote } from './shell-quote'
import { writeFileAtomic } from './write-file-atomic'

export interface WrapperTargets {
  /** The running app's `process.execPath`. */
  electronBinary: string
  /** Absolute path of the built CLI entry (`out/cli/index.js`). */
  cliEntry: string
  /** The data dir this app runs on (see below). */
  dataDir: string
  /**
   * The file the wrapper tests for presence instead of `cliEntry`, when the CLI sits inside an
   * archive: a shell cannot `test` into app.asar, and the archive is what disappears when the app
   * is moved or deleted. Set from the layout (resolveWrapperTargets), never guessed from the path.
   */
  presenceFile?: string
}

export interface LayoutInputs {
  /** `app.isPackaged`. */
  isPackaged: boolean
  /** `process.execPath`: the Electron binary in dev, the app's own executable once packaged. */
  execPath: string
  /** `process.resourcesPath`; only read when packaged (in dev it points into node_modules/electron). */
  resourcesPath: string
  /** Directory of the running main bundle (`__dirname` of out/main/index.js). */
  mainDir: string
  dataDir: string
}

/**
 * Where the CLI entry lives in this run. Packaged, the build output sits in the app archive,
 * `<resources>/app.asar/out/cli/index.js` (electron-builder.yml packs `out/` there), and main
 * reaches it through `process.resourcesPath`. In dev, and under `electron .` after a build, it is
 * `out/cli/index.js` beside `out/main/`. Electron run as Node (ELECTRON_RUN_AS_NODE) reads files
 * inside app.asar like the app does, so the archive path can be handed to it as it is.
 */
export function resolveWrapperTargets(input: LayoutInputs): WrapperTargets {
  if (!input.isPackaged) {
    return { electronBinary: input.execPath, cliEntry: join(input.mainDir, '..', 'cli', 'index.js'), dataDir: input.dataDir }
  }
  const archive = join(input.resourcesPath, 'app.asar')
  return {
    electronBinary: input.execPath,
    cliEntry: join(archive, 'out', 'cli', 'index.js'),
    dataDir: input.dataDir,
    presenceFile: archive
  }
}

/**
 * `CC_COCKPIT_DATA_DIR` is set to this app's data dir so that a tokenless call (a terminal
 * outside the app, through the `~/.local/bin/ccc` symlink) computes the same socket path as main
 * when the app was started with a data-dir override that terminal never saw. Tabs of every kind
 * and terminal overlays carry a token and get CC_COCKPIT_SOCK from main only while it listens
 * there (pty-env.ts), so they never compute a path. The wrapper does not carry CC_COCKPIT_SOCK:
 * it is written before the server binds, and a path main failed to bind must never reach a tab
 * (Task 12 review). A tokenless call to an app started with `$CC_COCKPIT_SOCK` then computes
 * `<data>/app.sock`, misses that app and exits 0 like any call that finds no app. A
 * `$CC_COCKPIT_SOCK` already in the caller's own environment still wins inside the CLI (paths.ts).
 *
 * The two file checks keep the "never fail a Claude hook" invariant (CLAUDE.md) when the build is
 * gone or half-written (a dev rebuild empties out/, the app was moved or deleted): `exec` on a
 * missing binary exits 126/127, and Electron-as-Node on a missing entry exits 1. A CLI inside
 * app.asar is checked by its archive (`presenceFile`).
 * `exec`: no shell stays between Claude and the CLI, so its exit code and signals pass straight through.
 */
export function wrapperScript({ electronBinary, cliEntry, dataDir, presenceFile }: WrapperTargets): string {
  return [
    '#!/bin/sh',
    '# Generated by cc-cockpit at every start; edits are overwritten.',
    `[ -f ${shellQuote(presenceFile ?? cliEntry)} ] || exit 0`,
    `[ -x ${shellQuote(electronBinary)} ] || exit 0`,
    `CC_COCKPIT_DATA_DIR=${shellQuote(dataDir)} ELECTRON_RUN_AS_NODE=1 exec ${shellQuote(electronBinary)} ${shellQuote(cliEntry)} "$@"`,
    ''
  ].join('\n')
}

export function writeCccWrapper(wrapperPath: string, targets: WrapperTargets): void {
  writeFileAtomic(wrapperPath, wrapperScript(targets), 0o755)
}
