// Bundles the editor's file tab page into plugins/editor/dist/pages and emits the shared outside-path
// rule into plugins/editor/dist/lib (both committed, since a plugin ships built files and the app runs
// no build at install; dist/ is what the packaging filter ships). The rest of the host
// (plugins/editor/dist/host.js, dist/lib) is plain JS and needs no build. Two outputs:
//   pages/file.bundle.js    the page (src/page/file.js), loaded by dist/pages/file.html.
//   lib/outside-paths.js    src/shared/outside-paths.ts as CommonJS, required by dist/lib/files.js:
//                           one rule for main and the editor (design-download.md §1.2), core to plugin.
// Usage: node scripts/build-editor.mjs [distdir]  (default plugins/editor/dist; both outputs go below
// it, so the unit test rebuilds both into one temp dir).
//
// Deterministic on purpose, as build-reviewer.mjs is: test/unit/reviewer-plugin.test.ts rebuilds into
// a temp dir and compares bytes with the committed files. A fixed target, `absWorkingDir` set so no
// absolute path or user name lands in the output (the page's to the plugin folder; the rule's to the
// repo, so its path comment reads `src/shared/outside-paths.ts`), no legal comments (the CodeMirror
// and lezer packages are MIT, whose notices travel in node_modules).
// The page is a classic script (IIFE): the page loads it without type="module", and a sandboxed frame
// with an opaque origin is no place for module chunks. Minified: the page loads it at every mount.
// The rule is CommonJS for the plugin host's `require`, unminified so a reader of the shipped plugin
// sees the rule it runs.
import { build } from 'esbuild'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoDir = join(dirname(fileURLToPath(import.meta.url)), '..')
const pluginDir = join(repoDir, 'plugins', 'editor')
const distDir = resolve(process.argv[2] ?? join(pluginDir, 'dist'))

await build({
  absWorkingDir: pluginDir,
  entryPoints: ['src/page/file.js'],
  outfile: join(distDir, 'pages', 'file.bundle.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'chrome120',
  minify: true,
  legalComments: 'none',
  logLevel: 'error'
})

await build({
  absWorkingDir: repoDir,
  entryPoints: ['src/shared/outside-paths.ts'],
  outfile: join(distDir, 'lib', 'outside-paths.js'),
  bundle: true,
  format: 'cjs',
  platform: 'node',
  target: 'node20',
  minify: false,
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build-editor.mjs from src/shared/outside-paths.ts; do not edit (npm run build:editor).' },
  logLevel: 'error'
})
