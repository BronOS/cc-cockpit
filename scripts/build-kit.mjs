// Builds the overlay kit (kit/README.md): the page side kit/src -> kit/dist/cc-kit.js (a classic script, IIFE,
// global `ccKit`) and kit/dist/cc-kit.css, then kit/SHA256SUMS over what a plugin vendors (the two dist files,
// host/shared-page.js, VERSION). All committed: plugins copy these bytes and pin them by SHA256SUMS.
// Usage: node scripts/build-kit.mjs [outdir]  (default kit/; test/unit/kit-build.test.ts builds into a temp dir and
// compares the bytes).
//
// Deterministic, as build-editor.mjs is: a fixed target, `absWorkingDir` so no absolute path lands in the output,
// no legal comments from the sources (the banner names markdown-it's licence instead). Not minified: a plugin's
// reviewer reads the vendored file.
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoDir = join(dirname(fileURLToPath(import.meta.url)), '..')
const kitDir = join(repoDir, 'kit')
const outDir = resolve(process.argv[2] ?? kitDir)

const version = readFileSync(join(kitDir, 'VERSION'), 'utf8').trim()
const srcVersion = readFileSync(join(kitDir, 'src', 'version.mjs'), 'utf8')
if (!srcVersion.includes(`'${version}'`)) throw new Error(`kit/src/version.mjs does not say ${version} (kit/VERSION)`)

const banner =
  `// cc-cockpit overlay kit ${version} (kit/README.md). Generated by scripts/build-kit.mjs from kit/src; do not edit.\n` +
  '// Bundles markdown-it and its dependencies (MIT licence: https://github.com/markdown-it/markdown-it/blob/master/LICENSE).'

await build({
  absWorkingDir: kitDir,
  entryPoints: ['src/index.mjs'],
  outfile: join(outDir, 'dist', 'cc-kit.js'),
  bundle: true,
  format: 'iife',
  globalName: 'ccKit',
  platform: 'browser',
  target: 'chrome120',
  minify: false,
  legalComments: 'none',
  charset: 'utf8',
  banner: { js: banner },
  logLevel: 'error',
})

mkdirSync(join(outDir, 'dist'), { recursive: true })
const css = readFileSync(join(kitDir, 'src', 'cc-kit.css'), 'utf8')
writeFileSync(join(outDir, 'dist', 'cc-kit.css'), `/* cc-cockpit overlay kit ${version}. Copied from kit/src/cc-kit.css by scripts/build-kit.mjs; do not edit. */\n${css}`)

// What a plugin vendors, hashed: the built files from outDir, the hand-written ones from kit/.
const hashed = [
  ['dist/cc-kit.css', join(outDir, 'dist', 'cc-kit.css')],
  ['dist/cc-kit.js', join(outDir, 'dist', 'cc-kit.js')],
  ['host/shared-page.js', join(kitDir, 'host', 'shared-page.js')],
  ['VERSION', join(kitDir, 'VERSION')],
]
const sums = hashed.map(([name, path]) => `${createHash('sha256').update(readFileSync(path)).digest('hex')}  ${name}`).join('\n')
writeFileSync(join(outDir, 'SHA256SUMS'), `${sums}\n`)
